// TestCreateShareSucceedsOnProTier is FEAT-046 AC1 at the API layer: any report can be shared via a
// stable link, and the link's token is unguessable (non-empty, generated by the handler).
func TestCreateShareSucceedsOnProTier(t *testing.T) {
	router, _, _, shares, _ := shareTestFixtures(t)

	req := authedRequest(t, http.MethodPost, "/v1/workspaces/ws-1/reports/report-1/shares", nil, "user-1", domain.TierPro)
	rec := httptest.NewRecorder()
	router.ServeHTTP(rec, req)

	if rec.Code != http.StatusCreated {
		t.Fatalf("status = %d, want %d, body = %s", rec.Code, http.StatusCreated, rec.Body.String())
	}

	var body struct {
		Share publicReportShare `json:"share"`
	}
	if err := json.Unmarshal(rec.Body.Bytes(), &body); err != nil {
		t.Fatalf("decoding response: %v", err)
	}
	if body.Share.ShareToken == "" {
		t.Error("share token is empty — the link would be unguessable-by-nothing")
	}
	if body.Share.ReportID != "report-1" {
		t.Errorf("report id = %q, want report-1", body.Share.ReportID)
	}
	if len(shares.byWorkspace["ws-1"]) != 1 {
		t.Errorf("stored shares = %d, want 1", len(shares.byWorkspace["ws-1"]))
	}
}


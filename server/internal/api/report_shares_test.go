// TestPublicSharedReportServesContentWithoutAuth is FEAT-046 AC2 at the API layer: an unauthenticated
// request with a valid token receives the report, its chart facts, and its provenance.
func TestPublicSharedReportServesContentWithoutAuth(t *testing.T) {
	router, reports, _, prov, steps := publicShareFixtures(t)
	report := reports.reports["report-1"]
	report.ProvenanceLinks = []string{"claim-1"}
	reports.reports["report-1"] = report
	prov.report = "report-1"
	prov.links = []domain.ProvenanceLink{makeProvenanceLink("claim-1", "report-1")}
	steps.steps["run-1"] = []domain.Step{{
		ID: "step-exec", RunID: "run-1", StepName: domain.StepExecute, Status: domain.StepComplete,
		Output: marshalExecuteJSON([]string{"region", "cnt"}, [][]any{{"North", float64(214)}}),
	}}

	req := httptest.NewRequest(http.MethodGet, "/v1/shared/reports/token-live", nil)
	rec := httptest.NewRecorder()
	router.ServeHTTP(rec, req)

	if rec.Code != http.StatusOK {
		t.Fatalf("status = %d, want %d, body = %s", rec.Code, http.StatusOK, rec.Body.String())
	}

	var body struct {
		Report struct {
			ID              string            `json:"id"`
			Title           string            `json:"title"`
			Narrative       string            `json:"narrative"`
			ProvenanceLinks []json.RawMessage `json:"provenance_links"`
			Reconciliation  struct{}          `json:"reconciliation_summary"`
			CreatedAt       string            `json:"created_at"`
		} `json:"report"`
		ExecuteResult *struct {
			Columns []string `json:"columns"`
			Rows    [][]any  `json:"rows"`
		} `json:"execute_result"`
	}
	if err := json.Unmarshal(rec.Body.Bytes(), &body); err != nil {
		t.Fatalf("decoding response: %v", err)
	}
	if body.Report.ID != "report-1" {
		t.Errorf("report id = %q, want report-1", body.Report.ID)
	}
	if body.Report.Narrative != "Revenue is $1.2M across 4 regions." {
		t.Errorf("narrative not served on the public view")
	}
	if len(body.Report.ProvenanceLinks) != 1 {
		t.Errorf("provenance links = %d, want 1 (provenance is part of the share)", len(body.Report.ProvenanceLinks))
	}
	if body.ExecuteResult == nil || len(body.ExecuteResult.Columns) != 2 {
		t.Errorf("execute_result not served — the shared chart needs the facts")
	}

	// The public payload must not leak workspace-internal identifiers.
	raw := rec.Body.String()
	for _, leak := range []string{`"workspace_id"`, `"run_id"`, `"parent_report_id"`, `"ws-1"`} {
		if strings.Contains(raw, leak) {
			t.Errorf("public response leaks %s", leak)
		}
	}
}

